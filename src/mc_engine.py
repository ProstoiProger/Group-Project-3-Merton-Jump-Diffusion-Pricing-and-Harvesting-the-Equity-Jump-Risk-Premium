"""Monte Carlo pricing engine for the Merton jump-diffusion model (W3).

Consolidates simulation, analytic pricing, variance-reduction experiments,
convergence studies, and plot renderers into a single production module.

Theory (W2 notation)
--------------------
    dX_t = (r - lambda*kappa - 0.5*sigma^2) dt + sigma dW_t + J dN_t
    kappa = E[exp(J) - 1] = exp(mu_j + 0.5*sigma_j^2) - 1

The Merton (1976) analytic formula is a Poisson-weighted Black-Scholes sum:
    C = sum_n  Pois(n; lambda'*T) * BS(S, K, T, r_n, sigma_n)

Entry point
-----------
    from src.mc_engine import write_outputs
    write_outputs(params, run_config, path_sizes, step_sizes, strikes)
"""

from __future__ import annotations

